/**
 * Writes lib/morpho/supply-tokens.ts: the tokens of the censused Morpho Blue markets on
 * Ethereum and Base that sit in a market with a supply of $1M or more. A token only Morpho
 * lists gets an asset card on /assets when it is in this list (Miles, 26 Oct 2026; rails-ops
 * TO-DO-ui-jobs 447 and reference/asset-key-map.md, "The asset explorer").
 *
 *   node --experimental-strip-types scripts/morpho-supply-tokens.mjs
 *
 * It runs at the end of every market census (scripts/census-morpho-markets.mjs), so the list
 * covers the markets the catalogs carry. Run it alone to refresh the supply read.
 *
 * Supply comes from Morpho's public API (api.morpho.org/graphql, `state.supplyAssetsUsd`, read
 * only): Rails stores no market's supply it serves. Only markets in the census files count, so
 * a market the API knows and the census does not is left out until the census is re-run.
 * Collateral and loan tokens both count. Symbols and decimals are not baked: the server reads
 * them through lib/sources/chain/erc20-meta.ts, the house resolver, cached.
 *
 * Needs no key and reads nothing from any box.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MORPHO_MARKETS as ETHEREUM } from "../lib/morpho/market-catalog.ts";
import { MORPHO_MARKETS as BASE } from "../lib/morpho-base/market-catalog.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "lib/morpho/supply-tokens.ts";
const API = "https://api.morpho.org/graphql";
const MIN_USD = 1_000_000;
const PAGE = 500;
const ZERO = /^0x0{40}$/;

const census = { 1: ETHEREUM, 8453: BASE };

async function page(skip) {
  const query = `{ markets(first: ${PAGE}, skip: ${skip}, where: { chainId_in: [1, 8453], supplyAssetsUsd_gte: ${MIN_USD} }) {
    pageInfo { countTotal }
    items { marketId chain { id } state { supplyAssetsUsd } }
  } }`;
  const res = await fetch(API, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ query }),
  });
  if (!res.ok) throw new Error(`Morpho API answered ${res.status}`);
  const body = await res.json();
  if (body.errors?.length) throw new Error(`Morpho API: ${body.errors[0].message}`);
  return body.data.markets;
}

const supply = new Map(); // `${chain}:${marketId}` → USD
for (let skip = 0; ; skip += PAGE) {
  const m = await page(skip);
  for (const it of m.items)
    if ((it.state?.supplyAssetsUsd ?? 0) >= MIN_USD)
      supply.set(`${it.chain.id}:${it.marketId.toLowerCase()}`, it.state.supplyAssetsUsd);
  if (skip + PAGE >= m.pageInfo.countTotal) break;
}

const tokens = {};
let markets = 0;
for (const [chain, list] of Object.entries(census)) {
  const best = new Map(); // token → its largest market's supply
  for (const m of list) {
    const usd = supply.get(`${chain}:${m.id.toLowerCase()}`);
    if (usd == null) continue;
    markets++;
    for (const t of [m.loanToken, m.collateralToken]) {
      const a = t.toLowerCase();
      if (!ZERO.test(a)) best.set(a, Math.max(best.get(a) ?? 0, usd));
    }
  }
  tokens[chain] = [...best].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([t]) => t);
}

const day = new Date().toISOString().slice(0, 10);
const list = (chain) => tokens[chain].map((t) => `    "${t}",`).join("\n");
const out = `// GENERATED by scripts/morpho-supply-tokens.mjs — do not edit by hand; re-run it.
//
// The tokens (collateral and loan) of the censused Morpho Blue markets with a supply of
// $${MIN_USD.toLocaleString("en-US")} or more, by chain, each chain's largest market first. A token only
// Morpho lists gets an asset card when it is here (lib/api/asset-explorer-chips.ts).
// Supply is Morpho's public API's \`state.supplyAssetsUsd\`, read on the day below.

/** The day the supply was read (UTC). */
export const MORPHO_SUPPLY_READ = "${day}";

/** Lowercased token addresses by chain id. */
export const MORPHO_SUPPLY_TOKENS: Readonly<Record<number, readonly string[]>> = {
  1: [
${list(1)}
  ],
  8453: [
${list(8453)}
  ],
};
`;
fs.writeFileSync(path.join(ROOT, OUT), out);
console.error(
  `wrote ${OUT}: ${markets} census markets at $${MIN_USD.toLocaleString("en-US")} or more; tokens: Ethereum ${tokens[1].length}, Base ${tokens[8453].length}`,
);
